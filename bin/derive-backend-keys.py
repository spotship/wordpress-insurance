#!/usr/bin/env python3
"""Extract the 201 key lists from the backend serializer. See the shell wrapper."""
import json
import re
import subprocess
import sys

backend = sys.argv[1]


def camel(name):
    head, *rest = name.split('_')
    return head + ''.join(part.title() for part in rest)


source = subprocess.run(
    ['git', '-C', backend, 'show', 'origin/dev:backend/insurance/serializers.py'],
    capture_output=True, text=True, check=True,
).stdout

provenance = re.search(r'PROVENANCE_FIELDS\s*=\s*([\[\(].*?[\]\)])', source, re.S)
provenance_fields = [camel(f) for f in re.findall(r'["\']([a-z_]+)["\']', provenance.group(1))]

out = {}
for match in re.finditer(r'class (\w+Serializer)\b.*?class Meta:(.*?)(?=\nclass |\Z)', source, re.S):
    name, meta = match.group(1), match.group(2)
    fields = re.search(r'fields\s*=\s*([\[\(].*?[\]\)])', meta, re.S)
    if not fields:
        continue
    literal = [camel(f) for f in re.findall(r'["\']([a-z_]+)["\']', fields.group(1))]
    out['cargo' if 'Cargo' in name else 'hull'] = literal + provenance_fields

sha = subprocess.run(
    ['git', '-C', backend, 'rev-parse', '--short', 'origin/dev'],
    capture_output=True, text=True, check=True,
).stdout.strip()

payload = {
    '_comment': [
        'GENERATED by bin/derive-backend-keys.sh from the backend source. Do not hand-edit.',
        'These are the keys a genuine 201 carries. A previous implementation hand-wrote a',
        'shape the API never emits, and the anti-bot decoy was then built to imitate the',
        'fixture — so the fixture being derived rather than written is the actual control.',
        'Derived from spotship/backend origin/dev @ ' + sha,
    ],
    'hull': out['hull'],
    'cargo': out['cargo'],
}

with open('tests/fixtures/backend-201-keys.json', 'w') as handle:
    json.dump(payload, handle, indent=2)
    handle.write('\n')

print('hull: %d  cargo: %d  from backend %s' % (len(out['hull']), len(out['cargo']), sha))
