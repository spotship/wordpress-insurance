#!/usr/bin/env python3
"""Extract the /api/insurance/rates/ payload from the backend source.

See the shell wrapper for why this is derived rather than written.

The endpoint returns ``rates.rates_payload()`` verbatim through
``CamelCaseJSONRenderer``, so reproducing it means camelising the zone and
column keys and rendering ``Decimal`` as a JSON number — which is what DRF
does here, NOT a preformatted percentage string. Getting that wrong is the
whole point of the exercise: a fixture that serves ``"8.500%"`` lets a
renderer that cannot format a number pass its own tests.
"""
import ast
import json
import re
import subprocess
import sys

backend = sys.argv[1]

WANTED = (
    'RATES_UPDATED_AT',
    'COMMON_DISCLAIMERS',
    'HULL_PORTAL_DISCLAIMER',
    'HULL_DISCLAIMERS',
    'CARGO_DISCLAIMERS',
    'HULL_FOOTNOTES',
    'HULL_ZONES',
    'CARGO_ZONES',
    'HULL_COLUMN_FIELDS',
    'HULL_COLUMN_LABELS',
    'CARGO_COLUMN_FIELDS',
    'CARGO_COLUMN_LABELS',
)


def camel(name):
    """The key transform CamelCaseJSONRenderer applies on the way out."""
    head, *rest = name.split('_')
    return head + ''.join(part.title() for part in rest)


source = subprocess.run(
    ['git', '-C', backend, 'show', 'origin/dev:backend/insurance/rates.py'],
    capture_output=True, text=True, check=True,
).stdout

# Execute ONLY the constant assignments, in a namespace holding nothing but
# Decimal. Importing the module would need Django settings and the camel-case
# package; regexing the zone literals would re-hand-write the shape in a second
# place, which is the failure this file exists to prevent.
module = ast.parse(source)
wanted = [
    node for node in module.body
    if isinstance(node, ast.Assign)
    and any(isinstance(t, ast.Name) and t.id in WANTED for t in node.targets)
]

if len(wanted) < len(WANTED):
    found = {t.id for node in wanted for t in node.targets if isinstance(t, ast.Name)}
    missing = sorted(set(WANTED) - found)
    sys.exit('derive-backend-rates: backend/insurance/rates.py no longer defines: ' + ', '.join(missing))

from decimal import Decimal  # noqa: E402  (only needed to evaluate the literals)

namespace = {'Decimal': Decimal}
exec(compile(ast.Module(body=wanted, type_ignores=[]), '<rates.py>', 'exec'), namespace)  # noqa: S102


def number(value):
    """Decimal -> JSON number, exactly as DRF renders it. None stays null."""
    return None if value is None else float(value)


def zone(row):
    return {camel(key): number(value) if isinstance(value, Decimal) else value
            for key, value in row.items()}


def columns(fields, labels):
    return [{'key': camel(field), 'label': label}
            for field, label in zip(fields, labels)]


sha = subprocess.run(
    ['git', '-C', backend, 'rev-parse', '--short', 'origin/dev'],
    capture_output=True, text=True, check=True,
).stdout.strip()

payload = {
    '_comment': [
        'GENERATED by bin/derive-backend-rates.sh from the backend source. Do not hand-edit.',
        'This is the body GET /api/insurance/rates/ returns. It was previously hand-written',
        'flat — a top-level `columns` list of plain strings and a top-level row list per',
        'product — a shape the API has never emitted, and the renderer and the whole e2e',
        'rate-table suite were built against it. Deriving it is the control.',
        'Derived from spotship/backend origin/dev @ ' + sha,
    ],
    'updatedAt': namespace['RATES_UPDATED_AT'],
    'hull': {
        'disclaimers': list(namespace['HULL_DISCLAIMERS']),
        'footnotes': list(namespace['HULL_FOOTNOTES']),
        'columns': columns(namespace['HULL_COLUMN_FIELDS'], namespace['HULL_COLUMN_LABELS']),
        'zones': [zone(row) for row in namespace['HULL_ZONES']],
    },
    'cargo': {
        'disclaimers': list(namespace['CARGO_DISCLAIMERS']),
        'footnotes': [],
        'columns': columns(namespace['CARGO_COLUMN_FIELDS'], namespace['CARGO_COLUMN_LABELS']),
        'zones': [zone(row) for row in namespace['CARGO_ZONES']],
    },
}

with open('tests/fixtures/backend-rates.json', 'w') as handle:
    json.dump(payload, handle, indent=2)
    handle.write('\n')

print('hull: %d zones / %d columns   cargo: %d zones / %d columns   from backend %s' % (
    len(payload['hull']['zones']), len(payload['hull']['columns']),
    len(payload['cargo']['zones']), len(payload['cargo']['columns']), sha))
