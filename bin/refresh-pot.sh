#!/usr/bin/env bash
#
# Regenerate languages/spotship-war-insurance.pot.
#
# ONE GENERATOR, BECAUSE THE CATALOGUE IS GATED BY REGENERATE-AND-DIFF.
#
# This used to prefer `wp i18n make-pot` when WP-CLI happened to be installed,
# and fall back to bin/extract-strings.js when it was not. The two do not
# produce the same file — make-pot writes `#:` source references, its own
# header and its own ordering — so ci.yaml's `Translation catalogue is current`
# job would have diffed non-empty and failed the moment a runner had WP-CLI,
# against a catalogue that was not stale at all. A gate that regenerates a file
# and compares it to the committed copy needs that file produced one way.
#
# make-pot is the better extractor: it parses PHP rather than matching it.
# Adopting it means adopting it wholesale — regenerate, commit the result, and
# make it the only path here — not leaving it as whichever one the machine
# happens to have.
#
# THE VERSION IS READ FROM THE PLUGIN HEADER, NOT WRITTEN DOWN AGAIN. It was
# hardcoded `0.1.0` in this file and shipped that way inside every zip through
# the 1.0.0 release, for the same reason readme.txt's `Stable tag` did.

set -euo pipefail

ROOT=$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )
OUT="$ROOT/languages/spotship-war-insurance.pot"
PLUGIN="$ROOT/spotship-war-insurance.php"

VERSION=$( sed -n 's/^ \* Version:[[:space:]]*\(.*\)$/\1/p' "$PLUGIN" | head -1 | tr -d '[:space:]' )

if [ -z "$VERSION" ]; then
	echo "refresh-pot: could not read the Version: header from $PLUGIN" >&2
	exit 1
fi

export SSWI_VERSION="$VERSION"

node "$ROOT/bin/extract-strings.js" "$ROOT" | node -e '
let raw = "";
process.stdin.on( "data", ( c ) => ( raw += c ) );
process.stdin.on( "end", () => {
	const strings = JSON.parse( raw );
	const esc = ( s ) => s.replace( /\\'"'"'/g, "'"'"'" ).replace( /"/g, "\\\"" );

	const header = [
		"# Copyright (C) 2026 Spot Ship",
		"# This file is distributed under the same licence as the Spot Ship War Insurance plugin.",
		"#",
		"# GENERATED by bin/refresh-pot.sh using the bin/extract-strings.js extractor.",
		"msgid \"\"",
		"msgstr \"\"",
		`"Project-Id-Version: Spot Ship War Insurance ${ process.env.SSWI_VERSION }\\n"`,
		"\"Report-Msgid-Bugs-To: https://github.com/spotship/wordpress-insurance/issues\\n\"",
		"\"MIME-Version: 1.0\\n\"",
		"\"Content-Type: text/plain; charset=UTF-8\\n\"",
		"\"Content-Transfer-Encoding: 8bit\\n\"",
		"\"X-Domain: spotship-war-insurance\\n\"",
		"",
	].join( "\n" );

	const body = strings.map( ( s ) => `msgid "${ esc( s ) }"\nmsgstr ""\n` ).join( "\n" );

	process.stdout.write( header + "\n" + body );
} );
' > "$OUT"

echo "refresh-pot: $VERSION ($(grep -c '^msgid' "$OUT") entries)"
