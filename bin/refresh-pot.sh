#!/usr/bin/env bash
#
# Regenerate languages/spotship-war-insurance.pot.
#
# Prefers WP-CLI, which is authoritative because it parses PHP rather than
# matching it. Falls back to the shared extractor in bin/extract-strings.js so
# the catalogue can be refreshed on a machine without WP-CLI — the fallback is
# conservative and the header says which produced the file.

set -euo pipefail

ROOT=$( cd "$( dirname "${BASH_SOURCE[0]}" )/.." && pwd )
OUT="$ROOT/languages/spotship-war-insurance.pot"

if command -v wp >/dev/null 2>&1; then
	wp i18n make-pot "$ROOT" "$OUT" --domain=spotship-war-insurance --exclude=tests,vendor,node_modules,dist
	echo "refresh-pot: generated with WP-CLI"
	exit 0
fi

node "$ROOT/bin/extract-strings.js" "$ROOT" | node -e '
let raw = "";
process.stdin.on( "data", ( c ) => ( raw += c ) );
process.stdin.on( "end", () => {
	const strings = JSON.parse( raw );
	const esc = ( s ) => s.replace( /\\'"'"'/g, "'"'"'" ).replace( /"/g, "\\\"" );

	const header = [
		"# Copyright (C) 2026 Spot Ship",
		"# This file is distributed under the same licence as the Spot Ship War Insurance plugin.",
		"#",
		"# GENERATED by bin/refresh-pot.sh using the bin/extract-strings.js fallback.",
		"# `wp i18n make-pot` is authoritative; run it when WP-CLI is available.",
		"msgid \"\"",
		"msgstr \"\"",
		"\"Project-Id-Version: Spot Ship War Insurance 0.1.0\\n\"",
		"\"Report-Msgid-Bugs-To: https://github.com/spotship/wordpress-insurance/issues\\n\"",
		"\"MIME-Version: 1.0\\n\"",
		"\"Content-Type: text/plain; charset=UTF-8\\n\"",
		"\"Content-Transfer-Encoding: 8bit\\n\"",
		"\"X-Domain: spotship-war-insurance\\n\"",
		"",
	].join( "\n" );

	const body = strings.map( ( s ) => `msgid "${ esc( s ) }"\nmsgstr ""\n` ).join( "\n" );

	process.stdout.write( header + "\n" + body );
} );
' > "$OUT"

echo "refresh-pot: generated with the node fallback ($(grep -c '^msgid' "$OUT") entries)"
