<?php
/**
 * Shortcode and block registration.
 *
 * Both surfaces delegate to `Spotship_WI_Renderer`, so there is exactly one
 * markup path and no way for a block to drift from a shortcode.
 *
 * @package Spotship_WI
 */

declare( strict_types = 1 );

defined( 'ABSPATH' ) || exit;

/**
 * Shortcodes and blocks.
 */
final class Spotship_WI_Shortcodes {

	/**
	 * Register both shortcodes.
	 */
	public static function register(): void {
		add_shortcode( 'spotship_war_hull', static fn() => Spotship_WI_Renderer::render( 'hull' ) );
		add_shortcode( 'spotship_war_cargo', static fn() => Spotship_WI_Renderer::render( 'cargo' ) );
	}

	/**
	 * The editor-side registration script handle.
	 *
	 * Named in each block.json's `editorScript`, which WordPress resolves as an
	 * already-registered handle when the value is not a `file:` path.
	 */
	public const EDITOR_SCRIPT = 'spotship-wi-blocks';

	/**
	 * Register both blocks.
	 *
	 * Server-rendered via the same renderer, so the block and the shortcode
	 * cannot drift.
	 *
	 * AN EDITOR SCRIPT IS NOT OPTIONAL, WHATEVER THE ATTRIBUTES ARE.
	 *
	 * The previous docblock here reasoned that `block.json` needed no
	 * `editorScript` "because there is nothing to configure: the block has no
	 * attributes". That conflates two different things. `register_block_type()`
	 * in PHP makes a block renderable and publishes its metadata, but WordPress
	 * has no PHP-only registration path for the EDITOR: the inserter is built
	 * from the client-side block registry, and nothing called
	 * `registerBlockType()` for either of these.
	 *
	 * So neither block appeared in the inserter, and a post that already
	 * contained one rendered as "this block contains unexpected or invalid
	 * content". The block surface did not work at all.
	 *
	 * The script is registered here rather than through `file:./index.js`
	 * because that form expects an `index.asset.php` listing dependencies, which
	 * is generated by a build step this plugin deliberately does not have. The
	 * dependencies are therefore named explicitly.
	 */
	public static function register_blocks(): void {
		wp_register_script(
			self::EDITOR_SCRIPT,
			SPOTSHIP_WI_URL . 'assets/js/blocks.js',
			array( 'wp-blocks', 'wp-element', 'wp-block-editor', 'wp-server-side-render' ),
			SPOTSHIP_WI_VERSION,
			true
		);

		foreach ( array( 'hull', 'cargo' ) as $product ) {
			$dir = SPOTSHIP_WI_PATH . 'blocks/' . $product;

			if ( ! is_readable( $dir . '/block.json' ) ) {
				continue;
			}

			register_block_type(
				$dir,
				array(
					'render_callback' => static fn() => Spotship_WI_Renderer::render( $product ),
				)
			);
		}
	}
}
